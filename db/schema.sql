-- ---- parameter_defs -------------------------------------------------
-- Governs which keys may appear in runs.parameters, renders the run form,
-- and tells the Phase 3 oracle which parameters are worth modelling on.
create table if not exists public.parameter_defs (
  id                       bigint generated by default as identity primary key,
  domain_id                text    not null references public.domains(id) on delete cascade,
  key                      text    not null,           -- the JSONB key, e.g. 'nozzle_temp'
  display_name             text    not null,
  group_name               text    not null default 'General',  -- form section heading
  data_type                text    not null default 'number'
                             check (data_type in ('number','integer','boolean','text','enum')),
  unit                     text,                       -- 'C', 'mm', 'mm/s', '%'
  min_value                numeric,
  max_value                numeric,
  step                     numeric,
  enum_options             text[],
  default_value            text,                       -- string form; cast per data_type in the UI
  is_required              boolean not null default false,
  is_calibration_relevant  boolean not null default false,
  help_text                text,
  sort_order               integer not null default 0,
  is_active                boolean not null default true,
  created_at               timestamptz not null default now(),
  constraint parameter_defs_domain_key_uniq unique (domain_id, key),
  constraint parameter_defs_key_shape
    check (key ~ '^[a-z][a-z0-9_]*$'),
  constraint parameter_defs_enum_has_options
    check (data_type <> 'enum' or (enum_options is not null and cardinality(enum_options) > 0)),
  constraint parameter_defs_range_sane
    check (min_value is null or max_value is null or min_value <= max_value)
);

comment on column public.parameter_defs.is_calibration_relevant is
  'Phase 3 reads only these keys when modelling what settings predict a good outcome.';


-- ---- defect_types ---------------------------------------------------
create table if not exists public.defect_types (
  id                 bigint generated by default as identity primary key,
  domain_id          text    not null references public.domains(id) on delete cascade,
  key                text    not null,                 -- 'stringing'
  display_name       text    not null,
  description        text,
  likely_causes      text[]  not null default '{}',    -- parameter_defs.key values, Phase 4 grounding
  is_process_related boolean not null default true,    -- false = external event (runout, power loss)
  sort_order         integer not null default 0,
  is_active          boolean not null default true,
  created_at         timestamptz not null default now(),
  constraint defect_types_domain_key_uniq unique (domain_id, key),
  constraint defect_types_key_shape check (key ~ '^[a-z][a-z0-9_]*$')
);

comment on column public.defect_types.is_process_related is
  'False for failures no setting could have prevented (filament runout, power cut, knocked part). '
  'Phase 2 costing counts them; Phase 3 calibration must NOT learn from them.';


