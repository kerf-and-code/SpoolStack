-- =====================================================================
-- 4. DERIVED COST VIEW  (this is the whole of Phase 2's plumbing)
-- =====================================================================
-- security_invoker = true is REQUIRED. Without it the view runs as its
-- owner and bypasses RLS on the underlying tables, exposing every user's
-- runs to every user. This is the single most dangerous line in the file.

drop view if exists public.run_cost_breakdown;

create view public.run_cost_breakdown
with (security_invoker = true) as
with base as (
  select
    r.id                as run_id,
    r.user_id,
    r.domain_id,
    r.project_id,
    r.machine_id,
    r.material_id,
    r.title,
    r.outcome,
    r.units_produced,
    r.units_good,
    r.duration_minutes,
    r.material_qty_used,
    r.material_qty_estimated,
    r.active_labor_minutes,
    r.created_at,
    mt.cost_per_unit    as material_cost_per_unit,
    mc.power_watts,
    mc.purchase_cost    as machine_purchase_cost,
    mc.expected_life_hours,
    mc.maintenance_cost_per_hour,
    us.electricity_rate_per_kwh,
    us.labor_rate_per_hour,
    us.include_labor_in_cost,
    us.currency
  from public.runs r
  left join public.materials     mt on mt.id      = r.material_id
  left join public.machines      mc on mc.id      = r.machine_id
  left join public.user_settings us on us.user_id = r.user_id
),
priced as (
  select
    base.*,
    round(base.material_qty_used * base.material_cost_per_unit, 4)
      as material_cost,
    round((base.power_watts / 1000.0)
          * (base.duration_minutes / 60.0)
          * base.electricity_rate_per_kwh, 4)
      as energy_cost,
    round(( (base.machine_purchase_cost / nullif(base.expected_life_hours, 0))
            + coalesce(base.maintenance_cost_per_hour, 0) )
          * (base.duration_minutes / 60.0), 4)
      as machine_cost,
    case
      when coalesce(base.include_labor_in_cost, false)
        then round((base.active_labor_minutes / 60.0) * base.labor_rate_per_hour, 4)
      else 0::numeric
    end as labor_cost,
    array_remove(array[
      case when base.duration_minutes is null          then 'duration_minutes' end,
      case when base.material_id is null               then 'material' end,
      case when base.material_qty_used is null         then 'material_qty_used' end,
      case when base.material_cost_per_unit is null    then 'material_cost_per_unit' end,
      case when base.machine_id is null                then 'machine' end,
      case when base.power_watts is null               then 'machine_power_watts' end,
      case when base.electricity_rate_per_kwh is null  then 'electricity_rate_per_kwh' end,
      case when base.machine_purchase_cost is null
             or base.expected_life_hours is null       then 'machine_depreciation_inputs' end,
      case when coalesce(base.include_labor_in_cost, false)
             and base.labor_rate_per_hour is null      then 'labor_rate_per_hour' end
    ], null) as missing_inputs
  from base
)
select
  priced.*,
  ( coalesce(priced.material_cost, 0)
  + coalesce(priced.energy_cost,   0)
  + coalesce(priced.machine_cost,  0)
  + coalesce(priced.labor_cost,    0) )                                   as total_cost,
  round(( coalesce(priced.material_cost, 0)
        + coalesce(priced.energy_cost,   0)
        + coalesce(priced.machine_cost,  0)
        + coalesce(priced.labor_cost,    0) )
        / nullif(priced.units_produced, 0), 4)                            as cost_per_unit_produced,
  round(( coalesce(priced.material_cost, 0)
        + coalesce(priced.energy_cost,   0)
        + coalesce(priced.machine_cost,  0)
        + coalesce(priced.labor_cost,    0) )
        / nullif(coalesce(priced.units_good, priced.units_produced), 0), 4)
                                                                          as cost_per_good_unit,
  (cardinality(priced.missing_inputs) = 0)                                as cost_complete
from priced;

comment on view public.run_cost_breakdown is
  'Phase 2 reads this. Costs recompute from current rates, so editing a material price or the '
  'power rate corrects every historical run. cost_complete/missing_inputs say when a number is '
  'partial rather than quietly summing zeros.';


