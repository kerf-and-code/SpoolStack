-- =====================================================================
-- SpoolStack (Maker Run Log) : Phase 1 "The Spine" schema
-- Target: Supabase Postgres 15+ (tested on PostgreSQL 16.13)
--
-- Run this whole file in the Supabase SQL editor. It is IDEMPOTENT:
-- running it twice is safe and changes nothing the second time.
--
-- Design contract (see the build plan doc):
--   * Rigid columns for what every run shares across FDM / CNC / resin / laser.
--   * A JSONB `parameters` bag for domain-specific settings.
--   * `parameter_defs` disciplines that bag AND drives the run form UI.
--   * Cost is NEVER stored. Runs store raw measurements; cost is derived
--     at read time by the run_cost_breakdown view.
--   * Adding a domain (CNC, resin, laser) = INSERT into reference tables.
--     No ALTER TABLE, no migration.
--
-- Section map:
--   0. Extensions and helpers
--   1. Reference tables (the template system): domains, parameter_defs, defect_types
--   2. User setup tables: user_settings, machines, materials, projects
--   3. The spine: runs, run_defects
--   4. Derived cost view
--   5. Indexes
--   6. Row Level Security
--   7. Grants
--   8. FDM seed data
-- =====================================================================


-- =====================================================================
-- 0. EXTENSIONS AND HELPERS
-- =====================================================================

-- gen_random_uuid() is in pg_catalog on PG13+; pgcrypto kept for older targets.
create extension if not exists pgcrypto with schema extensions;

-- NOTE: named dollar-quote tags throughout. Bare $$ has thrown
-- "unterminated dollar-quoted string" in the Supabase SQL editor.
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $set_updated_at$
begin
  new.updated_at = now();
  return new;
end;
$set_updated_at$;

comment on function public.set_updated_at() is
  'BEFORE UPDATE trigger: stamps updated_at. Returns NEW (never OLD) so the row actually writes.';


