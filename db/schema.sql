-- ---- runs -----------------------------------------------------------
-- One row per job: one print today, one CNC cut or laser pass later.
-- NOTE: no cost columns. Ever. See section 4.
create table if not exists public.runs (
  id                     uuid primary key default gen_random_uuid(),
  user_id                uuid not null references auth.users(id) on delete cascade,
  domain_id              text not null references public.domains(id),
  project_id             uuid references public.projects(id) on delete set null,
  machine_id             uuid references public.machines(id) on delete set null,
  material_id            uuid references public.materials(id) on delete set null,

  title                  text,
  started_at             timestamptz,
  completed_at           timestamptz,

  -- raw consumption measurements (cost inputs, never cost)
  duration_minutes       numeric(10,2) check (duration_minutes >= 0),
  material_qty_used      numeric(12,3) check (material_qty_used >= 0),
  material_qty_estimated boolean not null default false,  -- true when derived from length, not weighed
  active_labor_minutes   numeric(10,2) not null default 0 check (active_labor_minutes >= 0),

  -- batch economics: Phase 2's marginal-cost curve cannot be backfilled
  units_produced         integer not null default 1 check (units_produced > 0),
  units_good             integer check (units_good >= 0),

  outcome                text not null check (outcome in ('success','partial','failure','aborted')),
  quality_rating         smallint check (quality_rating between 1 and 5),

  parameters             jsonb not null default '{}'::jsonb,
  notes                  text,
  photos                 text[] not null default '{}',   -- storage object paths, Phase 4
  tags                   text[] not null default '{}',

  source                 text not null default 'manual'
                           check (source in ('manual','gcode_import','api')),
  source_metadata        jsonb not null default '{}'::jsonb,  -- the parser's raw matches

  created_at             timestamptz not null default now(),
  updated_at             timestamptz not null default now(),

  constraint runs_units_good_lte_produced
    check (units_good is null or units_good <= units_produced),
  constraint runs_completed_after_started
    check (started_at is null or completed_at is null or completed_at >= started_at),
  constraint runs_parameters_is_object
    check (jsonb_typeof(parameters) = 'object'),
  constraint runs_source_metadata_is_object
    check (jsonb_typeof(source_metadata) = 'object')
);

comment on table public.runs is
  'The event log. Every later feature is a query against this table, not a migration of it.';
comment on column public.runs.units_produced is
  'Parts on the plate. Required for per-unit cost and the Phase 2 economies-of-scale curve. '
  'Defaults to 1 so it never blocks a fast log entry, but it cannot be reconstructed later.';
comment on column public.runs.material_qty_estimated is
