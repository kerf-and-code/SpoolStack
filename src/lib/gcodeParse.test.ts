test('Cura: seconds, metres, and temperatures recovered from commands', () => {
  const r = parseGcode(CURA);
  assert.equal(r.durationMinutes, 62.05);
  assert.equal(r.materialEstimated, true);
  assert.equal(r.materialSource, 'from_length');
  // 3451.2mm of 1.75mm PLA -> pi*(0.875^2)*3451.2 mm3 = 8302.5 mm3 -> 10.29 g
  assert.ok(
    r.materialQtyUsedG !== null && Math.abs(r.materialQtyUsedG - 10.29) < 0.05,
    `expected ~10.29g, got ${r.materialQtyUsedG}`,
  );
  assert.equal(r.parameters.layer_height, 0.16);
  assert.equal(r.parameters.nozzle_temp, 205);
  assert.equal(r.parameters.bed_temp, 60);
  assert.equal(r.raw.nozzle_temp_source, 'M104/M109 command, not a settings comment');
});

