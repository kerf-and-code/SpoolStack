test('PrusaSlicer: duration, stated grams, and the settings block', () => {
  const r = parseGcode(PRUSA);
  assert.equal(r.durationMinutes, 62.05);
  assert.equal(r.materialQtyUsedG, 10.5);
  assert.equal(r.materialEstimated, false);
  assert.equal(r.materialSource, 'stated_grams');
  assert.equal(r.filamentType, 'PLA');
  assert.equal(r.printerModel, 'MK4');
  assert.match(r.slicer ?? '', /PrusaSlicer/);
  assert.equal(r.parameters.nozzle_temp, 210);
  assert.equal(r.parameters.first_layer_temp, 215);
  assert.equal(r.parameters.bed_temp, 60);
  assert.equal(r.parameters.layer_height, 0.2);
  assert.equal(r.parameters.retraction_distance, 0.8);
  assert.equal(r.parameters.retraction_speed, 35);
  assert.equal(r.parameters.print_speed, 45);
  assert.equal(r.parameters.wall_count, 3);
  assert.equal(r.parameters.infill_percent, 15);
  assert.equal(r.parameters.infill_pattern, 'gyroid');
  assert.equal(r.parameters.flow_rate, 98); // ratio 0.98 -> percent
  assert.equal(r.parameters.supports, false);
  assert.equal(r.parameters.bed_adhesion, undefined); // brim 0, raft 0, no brim_type
  assert.equal(r.warnings.length, 0);
});

