test('validateParameters drops keys the dictionary does not define', () => {
  const v = validateParameters({ nozzle_temp: 210, made_up_key: 5 }, FDM_DEFS);
  assert.equal(v.accepted.nozzle_temp, 210);
  assert.equal('made_up_key' in v.accepted, false);
  assert.equal(v.rejected.made_up_key, 'not defined for this domain');
});

test('validateParameters clamps out-of-range numbers and records the original', () => {
  const v = validateParameters({ nozzle_temp: 900, infill_percent: -4 }, FDM_DEFS);
  assert.equal(v.accepted.nozzle_temp, 350);
  assert.deepEqual(v.clamped.nozzle_temp, [900, 350]);
  assert.equal(v.accepted.infill_percent, 0);
});

test('validateParameters rejects an enum value outside enum_options', () => {
  const v = validateParameters({ infill_pattern: 'spaghetti' }, FDM_DEFS);
  assert.equal('infill_pattern' in v.accepted, false);
  assert.match(v.rejected.infill_pattern, /not one of/);
});

test('validateParameters rounds integers', () => {
  const v = validateParameters({ wall_count: 2.7 }, FDM_DEFS);
  assert.equal(v.accepted.wall_count, 3);
});

test('parseAndValidate returns only dictionary-legal keys', () => {
  const r = parseAndValidate(ORCA, FDM_DEFS);
  for (const key of Object.keys(r.parameters)) {
    assert.ok(
      FDM_DEFS.some((d) => d.key === key),
      `${key} is not in parameter_defs`,
    );
  }
  assert.equal(r.parameters.nozzle_temp, 245);
  assert.deepEqual(r.validation.rejected, {});
});

test('every parsed key across all fixtures exists in parameter_defs', () => {
  const known = new Set(FDM_DEFS.map((d) => d.key));
  for (const [name, fixture] of Object.entries({ PRUSA, ORCA, BAMBU_AMS, CURA })) {
    for (const key of Object.keys(parseGcode(fixture).parameters)) {
      assert.ok(known.has(key), `${name} produced unknown key: ${key}`);
    }
  }
});
