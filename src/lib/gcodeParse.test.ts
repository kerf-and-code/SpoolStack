test('hmsToMinutes handles every shape slicers emit', () => {
  assert.equal(hmsToMinutes('1h 2m 3s'), 62.05);
  assert.equal(hmsToMinutes('11m 6s'), 11.1);
  assert.equal(hmsToMinutes('45s'), 0.75);
  assert.equal(hmsToMinutes('2h'), 120);
  assert.equal(hmsToMinutes('1d 2h 30m'), 1590);
  assert.equal(hmsToMinutes('nonsense'), null);
  assert.equal(hmsToMinutes(null), null);
});

