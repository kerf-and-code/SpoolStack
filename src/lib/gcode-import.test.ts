const machines = [
  { id: 'm1', name: 'Garage P1S', make: 'Bambu Lab', model: 'P1S' },
  { id: 'm2', name: 'Office MK4', make: 'Prusa', model: 'MK4' },
  { id: 'm3', name: 'X', make: null, model: null },
];

test('machine match on model within the file string', () => {
  assert.deepEqual(matchMachines('Bambu Lab P1S', machines).map((m) => m.id), ['m1']);
  assert.deepEqual(matchMachines('MK4', machines).map((m) => m.id), ['m2']);
});

test('machine match ignores tiny tokens and missing models', () => {
  assert.deepEqual(matchMachines('Creality Ender-3 X', machines).map((m) => m.id), []);
  assert.deepEqual(matchMachines(null, machines), []);
});

const materials = [
  { id: 'a', name: 'Bambu Matte Black', category: 'PLA', brand: 'Bambu' },
  { id: 'b', name: 'Polymaker PLA Pro', category: 'PLA', brand: 'Polymaker' },
  { id: 'c', name: 'Overture PETG', category: 'PETG', brand: 'Overture' },
];

test('material: single category match is selected', () => {
  const r = matchMaterial('PETG', null, materials, '');
  assert.equal(r.kind, 'select');
  if (r.kind === 'select') assert.equal(r.material.id, 'c');
});

test('material: brand breaks a category tie', () => {
  const r = matchMaterial('PLA', 'Bambu PLA Matte @BBL P1S', materials, '');
  assert.equal(r.kind, 'select');
  if (r.kind === 'select') assert.equal(r.material.id, 'a');
});

test('material: a deliberate current choice in the category is kept', () => {
  const r = matchMaterial('PLA', 'Bambu PLA Matte', materials, 'b');
  assert.equal(r.kind, 'keep');
});

test('material: unresolved tie is ambiguous, not a guess', () => {
  const r = matchMaterial('PLA', null, materials, '');
  assert.equal(r.kind, 'ambiguous');
});

test('material: no category match', () => {
  assert.equal(matchMaterial('ASA', null, materials, '').kind, 'none');
  assert.equal(matchMaterial(null, null, materials, '').kind, 'none');
});
